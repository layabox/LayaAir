import fs from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { jsBytecodeTargets } from "./jsBytecodeTargets.mjs";

export const DEFAULT_MAX_BYTECODE_SIZE = 60 * 1024;
const worker = fileURLToPath(new URL("./checkJsBytecodeWorker.mjs", import.meta.url));

function measureFunction(file, functionName, runtime) {
    return new Promise((resolve, reject) => {
        const child = spawn(runtime, ["--no-lazy", "--print-bytecode", `--print-bytecode-filter=${functionName}`,
            "--no-warnings", "--experimental-vm-modules", worker, path.resolve(file)], {
            env: { ...process.env, ELECTRON_RUN_AS_NODE: "1" },
            stdio: ["ignore", "pipe", "pipe"], timeout: 120_000,
        });
        const records = [];
        let pending = "", stderr = "", active = false, complete = false, v8 = "", current;
        function finishFunction() {
            if (current) records.push(current);
            current = undefined;
        }
        function readLine(line) {
            if (line === "__LAYA_BYTECODE_BEGIN__") { active = true; return; }
            if (line.startsWith("__LAYA_BYTECODE_END__")) {
                finishFunction();
                v8 = line.slice(line.indexOf("V8=") + 3);
                complete = true;
                active = false;
                return;
            }
            if (!active) return;
            const header = /^\[generated bytecode for function: (.*?) \(/.exec(line);
            if (header) {
                finishFunction();
                current = { name: header[1] };
            }
            else if (current) {
                const length = /^Bytecode length: (\d+)/.exec(line);
                if (length) current.bytecodeSize = Number(length[1]);
                if (current.offset == null) {
                    const position = /^\s*(\d+)\s+[SE]>/.exec(line);
                    if (position) current.offset = Number(position[1]);
                }
            }
        }
        child.stdout.setEncoding("utf8");
        child.stdout.on("data", chunk => {
            pending += chunk;
            let newline;
            while ((newline = pending.indexOf("\n")) !== -1) {
                readLine(pending.slice(0, newline).replace(/\r$/, ""));
                pending = pending.slice(newline + 1);
            }
        });
        child.stderr.on("data", chunk => { stderr = (stderr + chunk).slice(-4096); });
        child.on("error", reject);
        child.on("close", (code, signal) => {
            if (pending) readLine(pending);
            if (code !== 0 || !complete)
                reject(new Error(`Bytecode inspection failed (${signal || code}): ${stderr.trim()}`));
            else resolve({ v8, records });
        });
    });
}

export async function inspectJsBytecode(file, {
    runtime = process.env.JS_BYTECODE_NODE || process.execPath,
    maxBytecodeSize = DEFAULT_MAX_BYTECODE_SIZE,
    targets = jsBytecodeTargets.find(item => item.file === path.basename(file))?.targets || [],
} = {}) {
    const result = { file, v8: "", checks: [], warnings: [], missingTargets: [] };
    if (!targets.length) return result;
    const source = await fs.promises.readFile(file, "utf8");
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
    const functions = [], exports = new Map();
    function visit(node) {
        if ((ts.isFunctionDeclaration(node) || ts.isMethodDeclaration(node)) && node.name)
            functions.push({ name: node.name.text,
                className: ts.isMethodDeclaration(node) && ts.isClassLike(node.parent) ? node.parent.name?.text : undefined,
                start: node.getStart(ast), end: node.end });
        if (ts.isPropertyAssignment(node) && ts.isIdentifier(node.initializer))
            exports.set(node.name.text, node.initializer.text);
        ts.forEachChild(node, visit);
    }
    visit(ast);
    const measurements = new Map();
    for (const target of targets) {
        const names = target.exportName ? [exports.get(target.exportName)]
            : target.methodName ? [target.methodName] : target.functionNames;
        const matches = functions.filter(fn => names?.includes(fn.name)
            && (!target.className || fn.className === target.className)
            && fn.end - fn.start >= (target.minSourceLength || 0));
        if (matches.length !== 1) {
            result.missingTargets.push({ label: target.label,
                reason: matches.length ? "ambiguous function match" : "function missing or source layout changed" });
            continue;
        }
        const fn = matches[0];
        // Shared filters compile generated helper groups once. Matching and warnings
        // still use only the individually configured function and source range.
        const filter = target.bytecodeFilter || fn.name;
        if (!measurements.has(filter)) measurements.set(filter, await measureFunction(file, filter, runtime));
        const measurement = measurements.get(filter);
        result.v8 = measurement.v8;
        const records = measurement.records.filter(record => record.name === fn.name && record.offset != null
            && record.offset >= fn.start && record.offset < fn.end
            && !functions.some(inner => inner.start > fn.start && inner.end <= fn.end
                && record.offset >= inner.start && record.offset < inner.end));
        if (records.length !== 1) {
            result.missingTargets.push({ label: target.label, reason: "V8 bytecode record missing or ambiguous" });
            continue;
        }
        const record = records[0];
        const location = ast.getLineAndCharacterOfPosition(record.offset);
        const check = { file, label: target.label, functionName: fn.name, bytecodeSize: record.bytecodeSize,
            maxBytecodeSize, line: location.line + 1, column: location.character + 1 };
        result.checks.push(check);
        if (check.bytecodeSize > maxBytecodeSize) result.warnings.push(check);
    }
    return result;
}

export async function warnJsBytecode(files, { warn = console.warn, ...options } = {}) {
    let count = 0;
    for (const file of [...new Set(files)].sort()) {
        try {
            const result = await inspectJsBytecode(file, options);
            for (const item of result.missingTargets) {
                count++;
                warn(`[WARNING][JS optimization] ${file}: target ${item.label}: ${item.reason}; review jsBytecodeTargets.mjs.`);
            }
            for (const item of result.warnings) {
                count++;
                warn(`[WARNING][JS optimization] ${path.relative(process.cwd(), file)}:${item.line}:${item.column}`
                    + ` ${item.label} (function ${item.functionName}): bytecode ${item.bytecodeSize} bytes > ${item.maxBytecodeSize} bytes.`
                    + ` May be too large for V8 optimization; consider splitting the function. (V8 ${result.v8})`);
            }
        }
        catch (error) {
            count++;
            warn(`[WARNING][JS optimization] ${file}: unable to inspect: ${error.message}`);
        }
    }
    return count;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const requestedFiles = process.argv.slice(2);
    const files = requestedFiles.length ? requestedFiles : jsBytecodeTargets.map(item =>
        fileURLToPath(new URL(`../src/layaAir/jsLibs/${item.file}`, import.meta.url)));
    console.log(`Checking fixed JS bytecode targets in ${files.length} libraries...`);
    const warnings = await warnJsBytecode(files);
    console.log(`JS bytecode check completed: ${warnings} warning(s).`);
}
